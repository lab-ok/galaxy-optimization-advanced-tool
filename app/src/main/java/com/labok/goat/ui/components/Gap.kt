package com.labok.goat.ui.components

import androidx.compose.ui.unit.dp

/**
 * 화면 간격 가이드라인. 모든 화면·시트의 세로 간격은 이 값만 쓴다(숫자 dp를 직접 쓰지 않는다, [GapGuideTest]가 검사).
 *
 * ```
 * ┌ 화면 가장자리 ── 좌우 16dp([featurePadding]·[SheetColumn])
 * │ ┌ 카드 ─ 안쪽 여백 [CardPadding] ──────────────┐
 * │ │ 제목                                          │
 * │ │ 설명(제목 바로 아래, 간격 없음)                │
 * │ │        ↕ [Item]   설명 → 조작(버튼·조절바·칩·그림) │
 * │ │ [버튼]                                        │
 * │ │        ↕ [Section] 카드 안의 다음 묶음         │
 * │ │ 제목 / 설명 / 스위치                            │
 * │ └──────────────────────────────────────────────┘
 * │        ↕ [Card]  카드와 카드, 목록 항목 사이, 섹션 제목 위
 * │ ┌ 카드 ...
 * ```
 *
 * 글 간격 규칙(줄 높이는 LiquidTheme의 LiquidType이 정한다):
 * 1. 좁은 것부터: 설명 줄 사이(약 3sp) < 제목↔설명(약 4.5sp) < [Tight](4dp+줄 여유) < [Item] < [Card] < [Section] < [Title].
 *    가까운 것일수록 더 좁게 붙여, 무엇이 한 덩어리인지 간격만으로 읽히게 한다.
 * 2. 제목과 설명, 그리고 같은 제목 아래 이어지는 설명 문단들은 한 덩어리라 Spacer를 넣지 않는다(줄 간격으로만 잇는다).
 *    보조 설명도 같은 글자 크기(bodySmall)로 설명 바로 아래에 둔다.
 * 3. [Tight]는 조작(조절바·버튼·칩) 바로 아래 붙는 작은 글(값 설명·힌트)에만 쓴다.
 * 4. 조절바는 높이 안에 위쪽 여백을 따로 두지 않는다(떠오르는 값 방울은 위 내용에 겹쳐 그린다).
 * - 시트의 큰 제목 아래는 [Title].
 * - 가로 간격(Row의 spacedBy, 아이콘과 글자 사이)은 이 규칙 밖이다.
 */
object Gap {
    /** 조작(조절바·버튼·칩) 바로 아래 붙는 작은 글(값 설명·힌트)과 그 조작 사이. 설명 문단 사이에는 쓰지 않는다. */
    val Tight = 4.dp

    /** 설명 글 → 그에 딸린 조작(버튼·조절바·칩·그림). */
    val Item = 10.dp

    /** 카드와 카드 사이, 목록 항목 사이, 섹션 제목 위. */
    val Card = 12.dp

    /** 한 카드 안에서 다음 설정 묶음으로 넘어갈 때. */
    val Section = 14.dp

    /** 시트의 큰 제목 아래. */
    val Title = 16.dp

    /** 카드 안쪽 여백(네 변 모두). */
    val CardPadding = 16.dp
}
